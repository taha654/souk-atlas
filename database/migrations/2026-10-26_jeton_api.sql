WHENEVER SQLERROR EXIT FAILURE
CREATE TABLE jeton_api (
    id                        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_utilisateur            NUMBER         NOT NULL,
    -- SHA-256 en hexadécimal : toujours 64 caractères
    empreinte                 CHAR(64)       NOT NULL,
    libelle                   VARCHAR2(100)  NOT NULL,
    date_creation             DATE           DEFAULT SYSDATE NOT NULL,
    date_expiration           DATE           NOT NULL,
    date_derniere_utilisation DATE,
    revoque                   NUMBER(1)      DEFAULT 0 NOT NULL,
    CONSTRAINT pk_jeton_api PRIMARY KEY (id),
    CONSTRAINT fk_jeton_api_utilisateur FOREIGN KEY (id_utilisateur) REFERENCES utilisateur (id) ON DELETE CASCADE,
    CONSTRAINT uq_jeton_api_empreinte UNIQUE (empreinte),
    CONSTRAINT ck_jeton_api_revoque CHECK (revoque IN (0, 1)),
    CONSTRAINT ck_jeton_api_dates CHECK (date_expiration > date_creation)
);
CREATE INDEX ix_jeton_api_utilisateur ON jeton_api (id_utilisateur);
EXIT
